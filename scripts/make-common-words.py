#!/usr/bin/env python3
"""Builds Sources/HunchHistory/CommonWordsData.swift: common lowercase English words, which Hunch
never learns on their own (see CommonWords.swift).

Sources (download by hand; credits and license notices are in THIRD-PARTY-NOTICES.md):
  - 12dicts 6.0.2 (Alan Beale, public domain): Lemmatized/2+2+3frq.txt, lemmas in frequency bands.
    http://wordlist.aspell.net/12dicts/
  - AGID 2016.01.19 (Kevin Atkinson): infl.txt, inflected forms (plurals, verb forms).
    http://wordlist.aspell.net/other/
  - SCOWL 2020.12.07 (Kevin Atkinson): final/, used only as a filter. A word is kept only when a
    lowercase SCOWL list of size <= --scowl-size has it (drops junk inflections and names).
    http://wordlist.aspell.net/

Steps: take every lemma (and the related forms indented under it) in bands 1..--max-band, add its
AGID inflections (confirmed part of speech, no questionable or variant tags, variant level <= 1),
keep only [a-z]+ words that pass the SCOWL filter. The output is sorted, so reruns are identical.

Usage: scripts/make-common-words.py <2+2+3frq.txt> <infl.txt> <scowl final/ dir>
                                    [--max-band 13] [--scowl-size 50] [--out path]
"""
import argparse, os, re

ap = argparse.ArgumentParser()
ap.add_argument('frq'); ap.add_argument('infl'); ap.add_argument('scowl')
ap.add_argument('--max-band', type=int, default=13)
ap.add_argument('--scowl-size', type=int, default=50)
ap.add_argument('--out', default='Sources/HunchHistory/CommonWordsData.swift')
a = ap.parse_args()
WORD = re.compile(r'[a-z]+')

# SCOWL lowercase lists (never upper, proper-names, abbreviations or contractions).
scowl = set()
for name in os.listdir(a.scowl):
    m = re.fullmatch(r'(english|american)-words\.(\d+)', name)
    if m and int(m.group(2)) <= a.scowl_size:
        for line in open(os.path.join(a.scowl, name), encoding='latin-1'):
            scowl.add(line.strip())

# AGID: lemma -> inflected forms.
inflections = {}
for line in open(a.infl, encoding='latin-1'):
    head, _, rest = line.partition(': ')
    lemma, pos = head.split(' ')[:2]
    if '?' in pos: continue
    forms = inflections.setdefault(lemma, set())
    for group in rest.split('|'):
        for entry in group.split(','):
            parts = entry.split()
            if not parts: continue
            form = parts[0]
            level = int(parts[1]) if len(parts) > 1 and parts[1].isdigit() else 0
            if level <= 1 and not any(c in form for c in '~<!?'): forms.add(form)

# 12dicts frequency bands.
words, band, lemmas = set(), 0, 0
for line in open(a.frq, encoding='latin-1'):
    m = re.match(r'-+ (\d+) -+', line)
    if m: band = int(m.group(1)); continue
    if band > a.max_band: continue
    for w in re.split(r',\s*', line.strip()):
        if not w or w.startswith('('): continue   # parenthesized: capitalized words, abbreviations
        w = w.rstrip('*!+')
        if not WORD.fullmatch(w): continue
        lemmas += not line.startswith(' ')
        words.update(f for f in {w} | inflections.get(w, set()) if WORD.fullmatch(f) and f in scowl)

out = sorted(words)
body = '\n'.join(' '.join(out[i:i + 16]) for i in range(0, len(out), 16))
open(a.out, 'w').write(
    '// Generated by scripts/make-common-words.py. Do not edit.\n'
    f'// {len(out)} common English words: 12dicts 6.0.2 2+2+3frq bands 1-{a.max_band} with AGID 2016.01.19\n'
    f'// inflections, kept when a lowercase SCOWL 2020.12.07 list of size <= {a.scowl_size} has them.\n'
    '// Credits and license notices: THIRD-PARTY-NOTICES.md.\n'
    'extension CommonWords {\n    static let frequentEnglishText = """\n' + body + '\n"""\n}\n')
print(f'{len(out)} words from {lemmas} lemmas -> {a.out}')
