import AppKit
import HunchCore
import HunchPolicy
import HunchScreen

/// Opt-in clipboard awareness (design §13): plain text the user copied in the last few minutes is
/// offered to the prompt as background. Skips anything a password manager marks concealed or
/// transient, single-token clipboards that look like passwords or codes, and secret-looking
/// lines; never reads during Secure Input. Nothing is stored beyond the current excerpt in memory.
@MainActor
final class ClipboardContextController {
    private let settings: () -> HunchSettings
    private let policies: any AppPolicyResolving
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var copiedAt: ContinuousClock.Instant?
    /// Where the copy was made: the app in front and its site when the copy was noticed, or
    /// unclear when the app changed since the previous poll.
    private var source: ClipboardSource?
    /// The frontmost app changed since the last poll.
    private var appSwitched = false
    private var activationObserver: (any NSObjectProtocol)?
    /// The focus engine's latest word on the app in front (set by the coordinator).
    var focus: ((_ frontmost: String?) -> ClipboardSource.Focus?)?
    /// Sanitized excerpt for `lastChangeCount`, computed once per copy.
    private var cached: (changeCount: Int, text: String?)?
    private var poller: Task<Void, Never>?

    /// How long copied text stays relevant.
    static let freshness: Duration = .seconds(300)
    static let maxCharacters = 1_500
    /// Pasteboard markers used by password managers and clipboard tools (nspasteboard.org).
    static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    init(settings: @escaping () -> HunchSettings, policies: any AppPolicyResolving) {
        self.settings = settings
        self.policies = policies
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] _ in
            MainActor.assumeIsolated { self?.appSwitched = true }
        }
        // changeCount is cheap to read; content is only read when a request needs it.
        poller = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: .seconds(1))
                guard let self else { return }
                let count = NSPasteboard.general.changeCount
                let switched = self.appSwitched
                self.appSwitched = false
                if count != self.lastChangeCount {
                    self.lastChangeCount = count
                    self.copiedAt = .now
                    let frontmost = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
                    self.source = ClipboardSource.noticed(frontmost: frontmost, appSwitchedSincePoll: switched,
                                                          focus: self.focus?(frontmost))
                    self.cached = nil
                }
            }
        }
    }

    /// Background text for a request, or nil (off, nothing recent, or not safe to use).
    func excerpt(for context: TextContext, policy: AppPolicy) -> String? {
        guard settings().clipboardContextEnabled, policy.enabled, !policy.secureExcluded,
              !SecureInputProbe.isSecureEventInputEnabled(),
              let copiedAt, ContinuousClock.now - copiedAt < Self.freshness else { return nil }
        // Text copied in an app or site Hunch is off or secure-excluded in, or where it can't
        // tell which app the copy came from, stays out of every app.
        guard let source, source.allows(policies) else { return nil }
        let board = NSPasteboard.general
        if let cached, cached.changeCount == board.changeCount { return cached.text }
        let types = Set((board.types ?? []).map(\.rawValue))
        let text: String? = if types.isDisjoint(with: Self.skipTypes), let raw = board.string(forType: .string) {
            Self.sanitize(raw)
        } else {
            nil
        }
        cached = (board.changeCount, text)
        return text
    }

    /// Lines like `DB_PASSWORD=...`, `api_key: ...`, `token = ...` (any case).
    static let assignmentSecret = try! NSRegularExpression(
        pattern: #"(pass(word|wd|phrase)?|secret|token|api[_-]?key|private[_-]?key|access[_-]?key|auth|credential|pin)\s*[:=]"#,
        options: [.caseInsensitive])

    static func sanitize(_ raw: String) -> String? {
        // Bound the work first: a huge clipboard must not stall typing.
        let trimmed = String(raw.prefix(maxCharacters * 4)).trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        if looksLikeCredential(trimmed) { return nil }
        // Whole-text pass first: private key blocks span lines.
        let lines = SecretSanitizer.redact(trimmed).split(whereSeparator: \.isNewline).compactMap { line -> String? in
            let text = String(line)
            let range = NSRange(text.startIndex..., in: text)
            if assignmentSecret.firstMatch(in: text, range: range) != nil { return nil }
            return SecretFilter.sanitize(text)
        }
        let joined = lines.joined(separator: "\n")
        guard joined.contains(where: { $0.isLetter }), !SecretSanitizer.isOnlyRedacted(joined) else { return nil }
        return String(joined.prefix(maxCharacters))
    }

    /// A single token (no spaces) of 6–64 characters mixing letters with digits or symbols: the
    /// shape of a copied password, key, or one-time code.
    static func looksLikeCredential(_ text: String) -> Bool {
        guard !text.contains(where: \.isWhitespace), (6...64).contains(text.count) else { return false }
        if text.allSatisfy(\.isNumber) { return true }   // OTPs and PINs
        let letters = text.contains(where: \.isLetter)
        let others = text.contains(where: { $0.isNumber || ($0.isPunctuation || $0.isSymbol) })
        let isURL = text.hasPrefix("http://") || text.hasPrefix("https://")
        return letters && others && !isURL
    }
}
